import { z } from "zod";
import { Id } from "./ids.ts";
import { PositiveQuantitySchema } from "./production.ts";
import { PublicationSchema, EntityId } from "./world-foundation.ts";

/**
 * Economy-owned Economic Holding / Account position and its reversible economic encumbrance — executable contracts
 * (OOC scenario / mechanism proof only).
 *
 * Governing source (exact pin lives in the owner registry and spec/f027/spec-lock.json):
 *   WS-004 Economy / Exchange / Demand (Working Operational Draft v1.1; lock pin 2026-09-24T11:45:02.825Z)
 *       §2.1 sparse Economic Holding / Account relations — `holder_ref`, `object_ref`, `quantity_or_bounded_position`
 *       where material, available / encumbered / restricted status, `restriction_or_authority_ref`,
 *       `lifecycle_status`, `provenance_ref`; Economy is the default owner-producer of holding and encumbrance state;
 *       §2.2 Economy does not own physical goods, legal entitlement validity, issuance authority, actor motive;
 *       §3 persistence rule and conserved-holding rule; §4 Economic Non-Interchangeability / No-Double-Spend (the
 *       same conserved holding may not fund two incompatible uses); §11 Economic Claim / Obligation lifecycle
 *       vocabulary (`active`, `cancelled`) — an encumbrance here is NOT a legal obligation; §20 Commitment and
 *       Conservation (verify the Economy-owned side is available and not already encumbered; prevent incompatible
 *       reuse; release unused economic encumbrance on cancellation; Economy never holds a physical reservation);
 *       §27.6 / §27.8 / §27.14 (authority, discretionary choice and downstream stages are other owners' and are not
 *       manufactured); §28 retention; §30 invariants 17–18, 27
 *
 * The bounded proof is ONE conserved position and its reversible partition:
 *
 *   scenario-opening premise (established before any hold)
 *     → separate OOC hold instruction → Economy checks actual current availability AS-OF-NOW and atomically
 *       partitions the SAME conserved position into available and encumbered
 *     → a later availability read / competing hold sees the changed state
 *     → separate OOC cancellation instruction of that still-active encumbrance → restored exactly once.
 *
 * Every schema is strict: an unmodelled field is rejected, never carried (IA-02). That is also the structural half
 * of the exclusions: the INPUT schemas below have no field in which a balance-after, an available/encumbered result,
 * a winner, an award, an approval, a `committed` flag or any other Economy conclusion could be supplied — Economy
 * derives the partition itself. There is no field for a price, a currency, a payment, a receipt, a settlement, a
 * legal title or priority, an entitlement, an issuance, a transfer, a physical reservation, a stock, a delivery, an
 * actor's intent or an in-world consent.
 *
 * The opening position is a separately authored OOC scenario premise, NOT an output generated by a payment intent
 * and not world-side wealth origination. An OOC instruction is not proof of the holder's in-world consent; both
 * records say so (`in_world_consent: NOT_ASSERTED`). Identifiers, owner/facet names and literals the sources do not
 * prescribe are technical encodings.
 */

// ---------------------------------------------------------------------------------------------
// Key spaces (IM-06, same Economy owner and facet as the demand chain). A holding is one slot per identity; an
// encumbrance is scoped to ITS holding, so a hold identity is exclusive within one holding and a foreign holding's
// hold identity can never address it.
// ---------------------------------------------------------------------------------------------

export const economyHoldingKey = (holdingId: string): string => `economy/holding/${holdingId}`;
export const economyEncumbranceKey = (holdingId: string, holdId: string): string =>
  `economy/encumbrance/${holdingId}/${holdId}`;

const Count = z.number().int().nonnegative().max(Number.MAX_SAFE_INTEGER);

/** The literal statements that keep the position from being mistaken for anything the sources assign elsewhere. */
export const HOLDING_POSITION_NATURE =
  "ECONOMIC_BOOK_POSITION_NOT_STOCK_TITLE_ISSUANCE_OR_RESERVATION";
export const ENCUMBRANCE_NATURE =
  "ECONOMIC_ENCUMBRANCE_NOT_PHYSICAL_RESERVATION_PAYMENT_SETTLEMENT_OR_LEGAL_PRIORITY";
export const OOC_OPENING_PREMISE = "OOC_SCENARIO_OPENING_PREMISE";
export const OOC_HOLD_INSTRUCTION = "OOC_SCENARIO_HOLD_INSTRUCTION";
export const OOC_CANCELLATION_INSTRUCTION = "OOC_SCENARIO_CANCELLATION_INSTRUCTION";

// ---------------------------------------------------------------------------------------------
// Economic Holding / Account relation (WS-004 §2.1). The bounded position is one exact partition of the ESTABLISHED
// amount into the three statuses the source names. `restricted` is representable only as zero and
// `restriction_or_authority_ref` only as null: restriction validity belongs to GIP / the surviving legal owner, and
// no producer of it exists in this tranche, so a restricted or authority-conditioned holding has no representation.
// Nothing enters or leaves the position (no issuance, transfer, payment, consumption, default or holder cessation
// exists here): available + encumbered + restricted = established, always.
// ---------------------------------------------------------------------------------------------

export const EconomyHoldingSchema = z
  .strictObject({
    holding_id: EntityId,
    /** the holder: an opaque identity of the economic locus; Economy does not own, create or validate the holder */
    holder_ref: EntityId,
    /** the economic object: an opaque identity; never a physical stock, title or currency definition */
    object_ref: EntityId,
    quantity_or_bounded_position: z.strictObject({
      unit: Id,
      /** the exact opening amount, fixed at establishment and never rewritten */
      established: z.number().int().positive().max(Number.MAX_SAFE_INTEGER),
      available: Count,
      encumbered: Count,
      restricted: z.literal(0),
    }),
    restriction_or_authority_ref: z.null(),
    lifecycle_status: z.literal("active"),
    /** where the opening position came from: the separately authored OOC premise, referenced by identity */
    provenance_ref: z.strictObject({
      kind: z.literal(OOC_OPENING_PREMISE),
      premise_id: EntityId,
    }),
    nature: z.literal(HOLDING_POSITION_NATURE),
  })
  .superRefine((h, ctx) => {
    const p = h.quantity_or_bounded_position;
    if (p.available + p.encumbered + p.restricted !== p.established)
      ctx.addIssue({
        code: "custom",
        message: "the position is conserved: available + encumbered + restricted = established",
        path: ["quantity_or_bounded_position"],
      });
  });
export type EconomyHolding = z.infer<typeof EconomyHoldingSchema>;

// ---------------------------------------------------------------------------------------------
// Encumbrance: one economic hold against one holding. Create-only apart from its single `active → cancelled`
// transition, which happens exactly once and records its own separate cancellation instruction. A cancelled record
// is retained: it is what makes a replayed or reused cancellation / hold identity refusable and the restoration
// exactly-once (WS-004 §28: retain while future-causal; a spent identity can still be misused).
// ---------------------------------------------------------------------------------------------

export const EconomyEncumbranceSchema = z
  .strictObject({
    encumbrance_id: EntityId,
    holding: z.strictObject({ fact_key: Id, holding_id: EntityId }),
    /** the holding version the hold was admitted against (AS-OF-NOW): the version it partitioned */
    admitted_at_holding_version: z.number().int().positive(),
    quantity: PositiveQuantitySchema,
    authorization: z.strictObject({
      basis: z.literal(OOC_HOLD_INSTRUCTION),
      instruction_id: EntityId,
      in_world_consent: z.literal("NOT_ASSERTED"),
    }),
    lifecycle_status: z.enum(["active", "cancelled"]),
    cancellation: z
      .strictObject({
        basis: z.literal(OOC_CANCELLATION_INSTRUCTION),
        instruction_id: EntityId,
      })
      .nullable(),
    nature: z.literal(ENCUMBRANCE_NATURE),
  })
  .superRefine((e, ctx) => {
    const bad = (message: string, path: string[]) =>
      ctx.addIssue({ code: "custom", message, path });
    if ((e.lifecycle_status === "cancelled") !== (e.cancellation !== null))
      bad("a cancelled encumbrance records its cancellation instruction, an active one has none", [
        "cancellation",
      ]);
    if (e.cancellation && e.cancellation.instruction_id === e.authorization.instruction_id)
      bad("the cancellation is a separate instruction from the hold it releases", [
        "cancellation",
        "instruction_id",
      ]);
  });
export type EconomyEncumbrance = z.infer<typeof EconomyEncumbranceSchema>;

// ---------------------------------------------------------------------------------------------
// Authored inputs. None carries an Economy conclusion.
// ---------------------------------------------------------------------------------------------

/** The scenario-opening premise: who holds how much of which object, and the premise it came from. */
export const EstablishHoldingInputSchema = z.strictObject({
  holding_id: EntityId,
  holder_ref: EntityId,
  object_ref: EntityId,
  quantity: PositiveQuantitySchema,
  premise_id: EntityId,
});
export type EstablishHoldingInput = z.infer<typeof EstablishHoldingInputSchema>;

/**
 * An OOC hold instruction: a distinct hold identity and quantity against the committed holding AT the version the
 * instruction saw. Whether the hold is admitted, and the resulting available/encumbered amounts, are Economy's.
 */
export const HoldInstructionInputSchema = z.strictObject({
  holding_id: EntityId,
  holding_version: z.number().int().positive(),
  hold_id: EntityId,
  instruction_id: EntityId,
  quantity: PositiveQuantitySchema,
});
export type HoldInstructionInput = z.infer<typeof HoldInstructionInputSchema>;

/** An OOC cancellation instruction naming one hold of one holding at the encumbrance version it saw. */
export const ReleaseInstructionInputSchema = z.strictObject({
  holding_id: EntityId,
  hold_id: EntityId,
  encumbrance_version: z.number().int().positive(),
  instruction_id: EntityId,
});
export type ReleaseInstructionInput = z.infer<typeof ReleaseInstructionInputSchema>;

/** What a hold or a release publishes: identities only. Labels are inherited from the holding, never defaulted. */
export const HoldingActPublicationSchema = PublicationSchema.pick({
  group_id: true,
  intent_id: true,
  cause: true,
});
export type HoldingActPublication = z.infer<typeof HoldingActPublicationSchema>;
