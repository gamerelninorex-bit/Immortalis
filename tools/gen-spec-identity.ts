import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const LOCK = "spec/f027/spec-lock.json";
const OUT = "packages/contracts/src/spec-identity.ts";

/** Renders the generated module text for the current spec-lock.json. */
export function renderSpecIdentity(root: string): string {
  const raw = readFileSync(join(root, LOCK), "utf8").replace(/\r\n/g, "\n");
  const lock = JSON.parse(raw) as {
    line: string;
    package: { version: string; native_pin: string };
    snapshot_files: Record<string, string>;
  };
  const identity = {
    line: lock.line,
    package_version: lock.package.version,
    package_native_pin: lock.package.native_pin,
    spec_lock_sha256: createHash("sha256").update(raw, "utf8").digest("hex"),
    snapshot_files: lock.snapshot_files,
  };
  return `// GENERATED by tools/gen-spec-identity.ts from ${LOCK}. Do not edit by hand.
// Regenerate: node --experimental-strip-types tools/gen-spec-identity.ts
import type { SpecIdentity } from "./spec-identity-schema.ts";

/** Identity of the F-027 spec line this build implements (IA-01). */
export const BUILD_SPEC_IDENTITY: SpecIdentity = ${JSON.stringify(identity, null, 2)};
`;
}

const isMain =
  process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  writeFileSync(join(root, OUT), renderSpecIdentity(root));
  console.log(`wrote ${OUT}`);
}
