import { canonicalJson } from "@immortalis/contracts";
import type { ReviewRequest } from "../../../packages/operator/src/review-evidence.ts";
import { CollectionPreparationSchema } from "../../../packages/operator/src/collection-preparation.ts";
import { ClosedSettingSchema } from "../../../packages/operator/src/closed-setting.ts";
import { StartingChronologySchema } from "../../../packages/operator/src/time-initialization.ts";
import type { OpeningSources } from "./reviews.ts";
import type { PlannedRun } from "./route-plan.ts";
const record = (x: unknown): x is Record<string, unknown> =>
  !!x && typeof x === "object" && !Array.isArray(x);
const same = (a: unknown, b: unknown) =>
  a !== undefined && b !== undefined && canonicalJson(a) === canonicalJson(b);
/** A later GM reading can realize only the exact reviewed native entry; other interpretations remain blocked. */
export function entryEvidence(source: OpeningSources, request: ReviewRequest): boolean {
  const entry = source.generation;
  if (!entry?.presence || !entry.pc || !entry.world || !entry.locus) return false;
  let subject: Record<string, unknown>;
  try {
    subject = JSON.parse(request.subject);
  } catch {
    return false;
  }
  if (
    subject.campaign_id !== source.campaign ||
    subject.pc_id !== entry.pc ||
    subject.world_id !== entry.world ||
    subject.locus_id !== entry.locus ||
    subject.statement !== entry.presence
  )
    return false;
  const reading = request.interpretation;
  if (!record(reading)) return false;
  if (request.verb === "place-character")
    return (
      record(reading.reading) &&
      reading.reading.mode === "NATIVE_ALREADY_THERE" &&
      reading.clarification === null
    );
  if (request.verb === "establish-character-locus")
    return (
      record(reading.embodiment) &&
      reading.embodiment.mode === "SINGLE_MATERIAL_BODY" &&
      record(reading.presence) &&
      reading.presence.mode === "NATIVE_AT_THIS_LOCUS" &&
      Array.isArray(reading.external_claims) &&
      reading.external_claims.length === 0 &&
      reading.clarification === null
    );
  return false;
}
/** Technical documents are generated by the existing planner from current accepted claims, never approved by a model assertion. */
export function stageEvidence(
  source: OpeningSources,
  plan: PlannedRun,
  request: ReviewRequest,
): boolean {
  if (entryEvidence(source, request)) return true;
  let s: Record<string, unknown>;
  try {
    s = JSON.parse(request.subject);
  } catch {
    return false;
  }
  if (s.campaign_id !== source.campaign) return false;
  const id = plan.identity;
  if (
    id.kind === "CHRONOLOGY" &&
    request.verb === "initialize-time" &&
    same(source.setting?.chronology, plan.retain.chronology)
  ) {
    return same(s.chronology, StartingChronologySchema.parse(JSON.parse(id.setup.document)));
  }
  if (
    id.kind === "PREPARE" &&
    request.verb === "prepare-collection" &&
    id.pc_id === source.generation?.pc &&
    same(source.generation?.preparation, plan.retain.preparation)
  ) {
    const input = plan.retain.preparation;
    return (
      source.setting?.reserve_condition === input?.reserve_condition &&
      same(s.setup, CollectionPreparationSchema.parse(JSON.parse(id.setup.document)))
    );
  }
  if (
    id.kind === "DECLARE" &&
    request.verb === "declare-closed-setting" &&
    same(source.setting?.declaration, plan.retain.declaration)
  ) {
    return same(s.declaration, ClosedSettingSchema.parse(JSON.parse(id.document)));
  }
  return false;
}
